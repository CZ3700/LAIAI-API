-- Volcengine Ark Monitor (ark_accounts, ark_endpoint_bindings, ark_video_tasks)
-- and Asset Conversion / Relay (upstream_asset_bindings, plugin_asset_groups, plugin_assets)

CREATE TABLE IF NOT EXISTS ark_accounts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL UNIQUE,
    volc_account_id VARCHAR(128) NOT NULL DEFAULT '',
    access_key VARCHAR(255) NOT NULL,
    secret_key_enc TEXT NOT NULL,
    secret_key_mask VARCHAR(64) NOT NULL DEFAULT '',
    region VARCHAR(64) NOT NULL DEFAULT 'cn-beijing',
    remark TEXT NOT NULL DEFAULT '',
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS ark_endpoint_bindings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id BIGINT NOT NULL REFERENCES ark_accounts(id) ON DELETE CASCADE,
    endpoint_id VARCHAR(128) NOT NULL,
    org_id BIGINT NOT NULL,
    user_id BIGINT NOT NULL DEFAULT 0,
    user_uid VARCHAR(128) NOT NULL DEFAULT '',
    api_key_enc TEXT NOT NULL DEFAULT '',
    api_key_mask VARCHAR(64) NOT NULL DEFAULT '',
    used_quota NUMERIC(20,8) NOT NULL DEFAULT 0,
    wallet_charged_quota NUMERIC(20,8) NOT NULL DEFAULT 0,
    wallet_ledger_after TIMESTAMPTZ,
    status SMALLINT NOT NULL DEFAULT 1,
    fuse_reason VARCHAR(32) NOT NULL DEFAULT '',
    remark TEXT NOT NULL DEFAULT '',
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (account_id, endpoint_id)
);

CREATE INDEX IF NOT EXISTS idx_ark_bindings_org ON ark_endpoint_bindings (org_id);
CREATE INDEX IF NOT EXISTS idx_ark_bindings_endpoint ON ark_endpoint_bindings (endpoint_id);
CREATE INDEX IF NOT EXISTS idx_ark_bindings_account ON ark_endpoint_bindings (account_id);

CREATE TABLE IF NOT EXISTS ark_video_tasks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id BIGINT NOT NULL,
    endpoint_id VARCHAR(128) NOT NULL DEFAULT '',
    task_id VARCHAR(128) NOT NULL UNIQUE,
    model VARCHAR(255) NOT NULL DEFAULT '',
    status VARCHAR(64) NOT NULL DEFAULT '',
    duration DOUBLE PRECISION NOT NULL DEFAULT 0,
    resolution VARCHAR(32) NOT NULL DEFAULT '',
    created_time VARCHAR(64) NOT NULL DEFAULT '',
    split_amount NUMERIC(20,8) NOT NULL DEFAULT 0,
    is_estimated BOOLEAN NOT NULL DEFAULT TRUE,
    total_tokens BIGINT NOT NULL DEFAULT 0,
    synced_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    raw_response TEXT NOT NULL DEFAULT '{}'
);

CREATE INDEX IF NOT EXISTS idx_ark_video_tasks_endpoint ON ark_video_tasks (endpoint_id);
CREATE INDEX IF NOT EXISTS idx_ark_video_tasks_account ON ark_video_tasks (account_id);
CREATE INDEX IF NOT EXISTS idx_ark_video_tasks_ep_estimated ON ark_video_tasks (endpoint_id) WHERE is_estimated = TRUE AND status IN ('succeeded', 'success');
CREATE INDEX IF NOT EXISTS idx_ark_video_tasks_ep_confirmed ON ark_video_tasks (endpoint_id) WHERE is_estimated = FALSE AND status IN ('succeeded', 'success');

CREATE TABLE IF NOT EXISTS upstream_asset_bindings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rid VARCHAR(32) NOT NULL UNIQUE,
    name VARCHAR(255) NOT NULL,
    source_type VARCHAR(32) NOT NULL DEFAULT 'channel',
    channel_config_id BIGINT NOT NULL DEFAULT 0,
    asset_base_path TEXT NOT NULL DEFAULT '',
    asset_protocol VARCHAR(32) NOT NULL DEFAULT 'ark_action',
    volc_ak VARCHAR(255) NOT NULL DEFAULT '',
    volc_sk_enc TEXT NOT NULL DEFAULT '',
    volc_sk_mask VARCHAR(64) NOT NULL DEFAULT '',
    volc_project_name VARCHAR(128) NOT NULL DEFAULT 'default',
    volc_region VARCHAR(64) NOT NULL DEFAULT 'cn-beijing',
    forward_rule_id BIGINT NOT NULL DEFAULT 0,
    group_id VARCHAR(128) NOT NULL DEFAULT '',
    is_active SMALLINT NOT NULL DEFAULT 1,
    remark TEXT NOT NULL DEFAULT '',
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_upstream_asset_bindings_config ON upstream_asset_bindings (channel_config_id);
CREATE INDEX IF NOT EXISTS idx_upstream_asset_bindings_rule ON upstream_asset_bindings (forward_rule_id);

CREATE TABLE IF NOT EXISTS plugin_asset_groups (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    org_id BIGINT NOT NULL,
    user_id BIGINT NOT NULL DEFAULT 0,
    group_id VARCHAR(128) NOT NULL,
    name VARCHAR(255) NOT NULL,
    description TEXT NOT NULL DEFAULT '',
    plugin_ns VARCHAR(64) NOT NULL DEFAULT 'asset_manager',
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (group_id, plugin_ns)
);

CREATE INDEX IF NOT EXISTS idx_plugin_asset_groups_org_ns ON plugin_asset_groups (org_id, plugin_ns);

CREATE TABLE IF NOT EXISTS plugin_assets (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    org_id BIGINT NOT NULL,
    user_id BIGINT NOT NULL DEFAULT 0,
    asset_type VARCHAR(32) NOT NULL,
    source VARCHAR(64) NOT NULL,
    status VARCHAR(32) NOT NULL DEFAULT 'approved',
    file_name VARCHAR(255) NOT NULL,
    file_url TEXT NOT NULL,
    asset_id VARCHAR(128) NOT NULL,
    group_id VARCHAR(128) NOT NULL DEFAULT '',
    category VARCHAR(64) NOT NULL DEFAULT '',
    content_hash VARCHAR(128) NOT NULL DEFAULT '',
    meta_fingerprint VARCHAR(128) NOT NULL DEFAULT '',
    plugin_ns VARCHAR(64) NOT NULL DEFAULT 'asset_manager',
    storage_provider VARCHAR(32) NOT NULL DEFAULT 'tos',
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_plugin_assets_meta_fp ON plugin_assets (meta_fingerprint, source, plugin_ns);
CREATE INDEX IF NOT EXISTS idx_plugin_assets_content_hash ON plugin_assets (content_hash, source, plugin_ns);
CREATE INDEX IF NOT EXISTS idx_plugin_assets_asset_ns ON plugin_assets (asset_id, plugin_ns);
CREATE INDEX IF NOT EXISTS idx_plugin_assets_org_ns ON plugin_assets (org_id, plugin_ns, id DESC);
