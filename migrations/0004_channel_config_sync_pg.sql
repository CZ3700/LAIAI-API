CREATE TABLE IF NOT EXISTS channel_config_sync_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    config_id BIGINT NOT NULL,
    upstream_system VARCHAR(64) NOT NULL DEFAULT '',
    upstream_group VARCHAR(128) NOT NULL DEFAULT '',
    upstream_ratio DOUBLE PRECISION NOT NULL DEFAULT 0,
    rate_add DOUBLE PRECISION NOT NULL DEFAULT 0,
    upstream_currency VARCHAR(16) NOT NULL DEFAULT '',
    site_currency VARCHAR(16) NOT NULL DEFAULT '',
    currency_rate DOUBLE PRECISION NOT NULL DEFAULT 1,
    previous_rate DOUBLE PRECISION NOT NULL DEFAULT 1,
    applied_rate DOUBLE PRECISION NOT NULL DEFAULT 1,
    sync_interval_minutes INTEGER NOT NULL DEFAULT 0,
    trigger_type VARCHAR(32) NOT NULL DEFAULT 'manual',
    status SMALLINT NOT NULL DEFAULT 1,
    error_message TEXT NOT NULL DEFAULT '',
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_channel_config_sync_logs_cfg_created
    ON channel_config_sync_logs (config_id, created_at DESC, id DESC);
